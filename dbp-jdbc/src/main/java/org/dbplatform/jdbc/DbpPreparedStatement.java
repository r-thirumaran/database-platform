    // ---------------------------------------------------------------- batch

    @Override
    public void addBatch() throws SQLException {
        checkOpen();
        paramBatch.add(snapshotParams());
    }

    @Override
    public void clearBatch() throws SQLException {
        super.clearBatch();
        paramBatch.clear();
    }

    @Override
    public long[] executeLargeBatch() throws SQLException {
        checkOpen();
        if (paramBatch.isEmpty()) {
            return new long[0];
        }
        try {
            ensurePrepared();
            List<List<Object>> sets = new ArrayList<>(paramBatch);
            try {
                return runBatch(ExecuteBatch.ofPrepared(statementId, kind, sets));
            } catch (SQLException e) {
                SQLException cause = e.getCause() instanceof SQLException c ? c : e;
                if (!isUnknownStatement(cause)) {
                    throw e;
                }
                statementId = ProtocolConstants.DIRECT_STATEMENT_ID;
                ensurePrepared();
                return runBatch(ExecuteBatch.ofPrepared(statementId, kind, sets));
            }
        } finally {
            paramBatch.clear();
        }
    }

    // ---------------------------------------------------------------- metadata

    @Override
    public ResultSetMetaData getMetaData() throws SQLException {
        checkOpen();
        DbpResultSet rs = currentResultSet();
        return rs == null || rs.isClosed() ? null : rs.getMetaData();
    }

    @Override
    public ParameterMetaData getParameterMetaData() throws SQLException {
        ensurePrepared();
        return new DbpParameterMetaData(parameterCount >= 0 ? parameterCount : params.size());
    }

    @Override
    protected void closeRemote() throws SQLException {
        if (statementId != ProtocolConstants.DIRECT_STATEMENT_ID) {
            int id = statementId;
            statementId = ProtocolConstants.DIRECT_STATEMENT_ID;
            connection.exchangeOk(new CloseStatement(id));
        }
    }

    // ---------------------------------------------------------------- parameters

    protected final void setParam(int index, Object value) throws SQLException {
        checkOpen();
        if (index < 1) {
            throw DbpSqlExceptions.invalidIndex("parameter index " + index + " must be >= 1");
        }
        if (parameterCount >= 0 && index > parameterCount) {
            throw DbpSqlExceptions.invalidIndex("parameter index " + index + " out of range 1.." + parameterCount);
        }
        while (params.size() < index) {
            params.add(UNSET);
        }
        params.set(index - 1, value);
    }

    private static Object orTypedNull(Object value, int jdbcType) {
        return value == null ? new TypedNull(jdbcType) : value;
    }

