    static int vendorType(SQLType type) throws SQLException {
        if (type == null || type.getVendorTypeNumber() == null) {
            throw DbpSqlExceptions.invalidArgument("SQLType without a vendor type number");
        }
        return type.getVendorTypeNumber();
    }

